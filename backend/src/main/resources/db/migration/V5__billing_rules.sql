CREATE TABLE fee_schemes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL UNIQUE,
    payer VARCHAR(120) NOT NULL,
    payer_email VARCHAR(254),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE billing_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheme_id BIGINT NOT NULL REFERENCES fee_schemes(id),
    type VARCHAR(20) NOT NULL CHECK (type IN ('APPLICATION', 'PERIODIC', 'SURCHARGE')),
    mode VARCHAR(10) NOT NULL CHECK (mode IN ('FIXED', 'PERCENT')),
    rate NUMERIC(18, 6) NOT NULL CHECK (rate > 0),
    effective_from DATE NOT NULL,
    due_days INTEGER NOT NULL CHECK (due_days BETWEEN 0 AND 3650),
    cycle_months INTEGER NOT NULL CHECK (cycle_months BETWEEN 1 AND 120),
    rounding_mode VARCHAR(12) NOT NULL CHECK (rounding_mode IN ('HALF_UP', 'HALF_EVEN', 'DOWN')),
    CHECK (type = 'SURCHARGE' OR mode = 'FIXED'),
    CHECK (type = 'PERIODIC' OR cycle_months = 1),
    UNIQUE (scheme_id, type, effective_from)
);

