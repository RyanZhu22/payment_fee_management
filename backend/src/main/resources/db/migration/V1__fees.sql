CREATE TABLE fees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(20) NOT NULL CHECK (type IN ('APPLICATION', 'PERIODIC', 'SURCHARGE')),
    application_number VARCHAR(64),
    scheme VARCHAR(120) NOT NULL,
    payer VARCHAR(120) NOT NULL,
    payer_email VARCHAR(254),
    description VARCHAR(240) NOT NULL,
    amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    due_date DATE NOT NULL,
    source_fee_id BIGINT UNIQUE REFERENCES fees(id),
    status VARCHAR(16) NOT NULL DEFAULT 'UNPAID' CHECK (status IN ('UNPAID', 'PAID', 'NON_PAYMENT')),
    settlement_date DATE,
    payment_method VARCHAR(64),
    bank_in_date DATE,
    reference_number VARCHAR(120),
    received_from VARCHAR(120),
    periodic_key VARCHAR(7) UNIQUE,
    CHECK ((type = 'SURCHARGE') = (source_fee_id IS NOT NULL))
);

CREATE INDEX fees_application_number_idx ON fees(application_number);
