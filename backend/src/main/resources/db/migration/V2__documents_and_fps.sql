CREATE SEQUENCE fee_document_number_seq;
CREATE SEQUENCE fps_request_number_seq;

CREATE TABLE fee_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fee_id BIGINT NOT NULL REFERENCES fees(id),
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('NOTICE', 'REMINDER', 'RECEIPT')),
    document_number VARCHAR(48) NOT NULL UNIQUE,
    generated_at TIMESTAMPTZ NOT NULL,
    generated_on DATE NOT NULL,
    delivery_status VARCHAR(16) NOT NULL DEFAULT 'NOT_SENT'
        CHECK (delivery_status IN ('NOT_SENT', 'SENT', 'BOUNCED')),
    recipient_email VARCHAR(254),
    bank_in_date DATE,
    amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    storage_key VARCHAR(255) NOT NULL,
    emailed_at TIMESTAMPTZ,
    bounce_reason VARCHAR(240)
);

CREATE UNIQUE INDEX fee_documents_receipt_fee_idx ON fee_documents(fee_id) WHERE kind = 'RECEIPT';
CREATE INDEX fee_documents_fee_idx ON fee_documents(fee_id);
CREATE INDEX fee_documents_generated_on_idx ON fee_documents(generated_on);
CREATE INDEX fee_documents_bank_in_date_idx ON fee_documents(bank_in_date);

CREATE TABLE fps_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fee_id BIGINT NOT NULL REFERENCES fees(id),
    request_number VARCHAR(48) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL,
    expires_on DATE NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('DEMO', 'EXPIRED', 'SETTLED')),
    qr_payload TEXT NOT NULL,
    request_data JSONB NOT NULL,
    response_data JSONB
);

CREATE INDEX fps_requests_fee_idx ON fps_requests(fee_id);
CREATE INDEX fps_requests_created_at_idx ON fps_requests(created_at);
