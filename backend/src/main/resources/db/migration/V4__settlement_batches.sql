CREATE TABLE settlement_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(8) NOT NULL CHECK (type IN ('APPLN', 'FEESU')),
    filename VARCHAR(255) NOT NULL,
    checksum VARCHAR(64) NOT NULL,
    original_file BYTEA NOT NULL,
    status VARCHAR(24) NOT NULL CHECK (status IN ('PENDING_REVIEW', 'VALIDATION_FAILED', 'APPROVED', 'REJECTED')),
    total INTEGER NOT NULL,
    successful INTEGER NOT NULL,
    failed INTEGER NOT NULL,
    amount NUMERIC(18,2) NOT NULL,
    created_by VARCHAR(120) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    reviewed_by VARCHAR(120),
    reviewed_at TIMESTAMPTZ,
    review_reason VARCHAR(1000),
    UNIQUE (type, checksum)
);

CREATE TABLE settlement_batch_rows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES settlement_batches(id),
    row_number INTEGER NOT NULL,
    matching_reference TEXT NOT NULL,
    fee_id BIGINT REFERENCES fees(id),
    amount NUMERIC(14,2),
    settlement_date DATE,
    payment_method VARCHAR(64),
    bank_in_date DATE,
    reference_number VARCHAR(120),
    received_from VARCHAR(120),
    valid BOOLEAN NOT NULL,
    message_zh VARCHAR(1000) NOT NULL,
    message_en VARCHAR(1000) NOT NULL,
    fee_snapshot TEXT,
    snapshot_hash VARCHAR(64),
    UNIQUE (batch_id, row_number)
);

CREATE TABLE settlement_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fee_id BIGINT NOT NULL REFERENCES fees(id),
    batch_row_id BIGINT UNIQUE REFERENCES settlement_batch_rows(id),
    amount NUMERIC(14,2) NOT NULL,
    settlement_date DATE,
    payment_method VARCHAR(64),
    bank_in_date DATE,
    reference_number VARCHAR(120),
    received_from VARCHAR(120),
    method_key VARCHAR(64),
    reference_key VARCHAR(120),
    legacy BOOLEAN NOT NULL DEFAULT FALSE,
    posted_by VARCHAR(120) NOT NULL,
    posted_at TIMESTAMPTZ NOT NULL,
    reversed_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX settlement_payments_active_fee_idx ON settlement_payments(fee_id) WHERE reversed_at IS NULL;
CREATE UNIQUE INDEX settlement_payments_active_reference_idx
    ON settlement_payments(method_key, reference_key) WHERE reversed_at IS NULL AND reference_key IS NOT NULL;

-- Existing PAID data retains its original fields. Its payment provenance is explicitly legacy.
INSERT INTO settlement_payments (fee_id, amount, settlement_date, payment_method, bank_in_date,
    reference_number, received_from, legacy, posted_by, posted_at)
SELECT id, amount, settlement_date, payment_method, bank_in_date,
    reference_number, received_from, TRUE, 'LEGACY_MIGRATION', CURRENT_TIMESTAMP
FROM fees WHERE status = 'PAID';

CREATE TABLE settlement_reversals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fee_id BIGINT NOT NULL REFERENCES fees(id),
    payment_id BIGINT NOT NULL REFERENCES settlement_payments(id),
    status VARCHAR(24) NOT NULL CHECK (status IN ('PENDING_REVIEW', 'APPROVED', 'REJECTED')),
    reason VARCHAR(1000) NOT NULL,
    created_by VARCHAR(120) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    reviewed_by VARCHAR(120),
    reviewed_at TIMESTAMPTZ,
    review_reason VARCHAR(1000)
);
CREATE UNIQUE INDEX settlement_reversals_pending_payment_idx
    ON settlement_reversals(payment_id) WHERE status = 'PENDING_REVIEW';

